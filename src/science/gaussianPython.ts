/**
 * Python source export for the Gaussian reference slice.
 *
 * Pure string construction with no framework dependencies: the browser can
 * build the downloadable/copyable source, and the verification suite can write
 * and execute exactly the same source in the isolated Python environment.
 */

import type { GaussianSnapshot } from "./gaussian";
import { validateGaussianSnapshot } from "./gaussian";

export const GAUSSIAN_PYTHON_FILENAME = "patlas_gaussian_snapshot.py";

const REQUIREMENTS = ["numpy==2.5.5", "scipy==1.18.1", "matplotlib==3.11.2"];

function pythonNumber(value: number): string {
  if (!Number.isFinite(value)) throw new RangeError("Python export requires finite numbers.");
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

/**
 * Build a self-contained script that reproduces the supplied snapshot with
 * SciPy/NumPy/Matplotlib and prints machine-readable values with --json.
 */
export function buildGaussianPythonSource(snapshot: GaussianSnapshot): string {
  const validation = validateGaussianSnapshot(snapshot);
  if (!validation.ok) {
    throw new RangeError(`Invalid Gaussian snapshot: ${validation.errors.join(" ")}`);
  }
  const { mu, sigma, domain } = validation.value;

  return `#!/usr/bin/env python3
"""PATLAS — Gaussian snapshot (generated).

Reproduces the parameter snapshot shown in the PATLAS Gaussian laboratory:

    mu    = ${pythonNumber(mu)}
    sigma = ${pythonNumber(sigma)}
    display domain = [${pythonNumber(domain.min)}, ${pythonNumber(domain.max)}]
    samples = ${domain.samples}

The Gaussian probability density function is

    f(x) = exp(-0.5 * ((x - mu) / sigma)^2) / (sigma * sqrt(2 * pi))

Density is not probability mass. The plotted window is finite; it is not the
support of the distribution and is not used as proof of normalization.

Requirements (identical to python/requirements.txt):
    ${REQUIREMENTS.join("\n    ")}

Install and run:
    python -m venv .venv
    .venv/bin/python -m pip install ${REQUIREMENTS.join(" ")}
    .venv/bin/python ${GAUSSIAN_PYTHON_FILENAME} --json
    .venv/bin/python ${GAUSSIAN_PYTHON_FILENAME} --plot gaussian.png

Generated by PATLAS (MIT licence for code). Educational text: CC BY 4.0.
"""

from __future__ import annotations

import argparse
import json
import math

import numpy as np
from scipy.stats import norm

MU = ${pythonNumber(mu)}
SIGMA = ${pythonNumber(sigma)}
X_MIN = ${pythonNumber(domain.min)}
X_MAX = ${pythonNumber(domain.max)}
SAMPLES = ${domain.samples}


def density(x: float) -> float:
    """Gaussian density at x for the snapshot parameters."""
    return float(norm.pdf(x, loc=MU, scale=SIGMA))


def grid():
    """Deterministic density samples over the displayed domain."""
    xs = np.linspace(X_MIN, X_MAX, SAMPLES)
    ys = norm.pdf(xs, loc=MU, scale=SIGMA)
    return xs, ys


def summary() -> dict:
    """Machine-readable reproduction of the laboratory snapshot."""
    xs, ys = grid()
    return {
        "mu": MU,
        "sigma": SIGMA,
        "mean": MU,
        "variance": SIGMA ** 2,
        "peak_density": 1.0 / (SIGMA * math.sqrt(2.0 * math.pi)),
        "density_at_mean": density(MU),
        "density_at_mean_plus_sigma": density(MU + SIGMA),
        "display_domain": {
            "min": float(xs[0]),
            "max": float(xs[-1]),
            "samples": int(SAMPLES),
        },
        "curve": [
            {"x": float(x), "y": float(y)} for x, y in zip(xs, ys)
        ],
    }


def write_plot(path: str) -> None:
    """Save the density plot using the same fixed axes as the PATLAS lab."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    xs, ys = grid()
    figure, axes = plt.subplots(figsize=(8.0, 4.0), dpi=150)
    axes.plot(xs, ys, color="#087F69", linewidth=2.0)
    axes.set_xlim(X_MIN, X_MAX)
    axes.set_ylim(0.0, 0.9)
    axes.set_xlabel("x")
    axes.set_ylabel("f(x)  probability density")
    axes.set_title("Gaussian density: mu = %.2f, sigma = %.2f" % (MU, SIGMA))
    axes.grid(True, alpha=0.3)
    figure.tight_layout()
    figure.savefig(path)
    plt.close(figure)


def main() -> int:
    parser = argparse.ArgumentParser(description="PATLAS Gaussian snapshot")
    parser.add_argument("--json", action="store_true", help="print JSON values")
    parser.add_argument("--plot", metavar="PATH", help="save a PNG plot")
    args = parser.parse_args()

    if args.plot:
        write_plot(args.plot)

    data = summary()
    if args.json:
        print(json.dumps(data, sort_keys=True))
    else:
        print("PATLAS Gaussian snapshot")
        print("mu        = %.4f" % data["mu"])
        print("sigma     = %.4f" % data["sigma"])
        print("mean      = %.4f" % data["mean"])
        print("variance  = %.4f" % data["variance"])
        print("peak f(x) = %.6f" % data["peak_density"])
        print("domain    = [%.1f, %.1f]" % (data["display_domain"]["min"], data["display_domain"]["max"]))
        print("Use --json for machine-readable output or --plot PATH for a figure.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
`;
}
